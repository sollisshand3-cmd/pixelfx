// Every word the player reads, in three languages: English (the default), Bahasa Malaysia and Bahasa
// Indonesia. Each entry is [en, ms, id]. t(key, vars) fills {name}-style slots; a key that isn't here comes
// back unchanged, so plain text can pass through.

export const LANGS = [
  { id: "en", name: "English" },
  { id: "ms", name: "Bahasa Malaysia" },
  { id: "id", name: "Bahasa Indonesia" },
];
const IDX = { en: 0, ms: 1, id: 2 };
let current = "en";
try {
  const saved = JSON.parse(localStorage.getItem("senyap-hotel:lang") ?? "null");
  if (saved && saved in IDX) current = saved;
} catch {}

export const lang = () => current;
export function setLang(l) {
  if (!(l in IDX)) return;
  current = l;
  try {
    localStorage.setItem("senyap-hotel:lang", JSON.stringify(l));
  } catch {}
  document.documentElement.lang = l;
}
export function has(key) {
  return key in D;
}
export function t(key, vars = {}) {
  if (typeof key !== "string") return key;
  // "key|arg" passes one argument as {0}
  const [k, arg] = key.split("|");
  const e = D[k];
  if (!e) return key;
  let s = e[IDX[current]] ?? e[0];
  if (arg !== undefined) s = s.replaceAll("{0}", arg);
  for (const [v, x] of Object.entries(vars)) s = s.replaceAll(`{${v}}`, x);
  return s;
}

